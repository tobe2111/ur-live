/**
 * 🏬 **몰 흔적(origin breadcrumb)** — "이 손님은 어느 가게에서 들어왔는가" (2026-08-02)
 *
 * 몰 손님의 동선은 `카톡 → urdeal.kr/{슬러그} → 상품 카드 → /products/{id}` 다.
 * 그런데 **상품 URL 에는 가게가 안 적혀 있다.** 평소엔 상관없지만 상품을 못 읽은 순간
 * (품절·삭제·일시 오류) 화면이 갈 곳을 잃고 **유어딜 홈**으로 보낸다 — 그건 `MallHomePage`
 * 주석이 *"몰이 열렸다보다 나쁜 결과"* 라고 못 박은 바로 그 결과다.
 *
 * ⇒ 몰 홈을 지나갈 때 슬러그를 한 조각 남겨 두고, 갈 곳이 없을 때만 꺼내 쓴다.
 *
 * ## 이 흔적으로 하지 말아야 할 것
 * 🔴 **몰 상품 판정에 쓰지 말 것.** 그건 `products.mall_id`(서버 데이터)가 한다.
 *   흔적은 클라 상태라 오래되거나 없을 수 있고, 그걸로 CTA 를 가르면 같은 상품이
 *   진입 경로에 따라 다르게 보인다 — 2026-06-18 flip-flop 사고와 같은 클래스다.
 *
 * ## 허용 용도 (2026-08-12 확장 — 대표 "완전 별개, 분리")
 *  1. **되돌아갈 곳** — 원래 용도.
 *  2. **유어딜 자기영업 억제** (`isFromMallSession`) — 아래 함수 참조.
 *
 * ⚠️ 둘의 공통점: **틀렸을 때 손해가 한쪽으로만 난다.** 상품 표시·가격·결제는 절대 이걸로 가르지 않는다.
 */
const KEY = 'ur_mall_origin'

/** 몰 홈을 열 때 호출. SSR·비브라우저에서는 조용히 no-op. */
export function rememberMallOrigin(slug: string | null | undefined): void {
  const s = String(slug ?? '').trim().toLowerCase()
  if (!s) return
  try { sessionStorage.setItem(KEY, s) } catch { /* 프라이빗 모드 등 — 흔적 없이 동작 */ }
}

/**
 * 마지막으로 지나온 몰 슬러그. 없으면 `null`.
 * ⚠️ 값을 **경로에 그대로 넣으므로** 문법을 다시 검사한다 — sessionStorage 는 사용자가 고칠 수 있다.
 */
export function readMallOrigin(): string | null {
  try {
    const s = String(sessionStorage.getItem(KEY) ?? '').trim().toLowerCase()
    return /^[a-z0-9-]{3,30}$/.test(s) ? s : null
  } catch { return null }
}

/**
 * 🔇 **이 세션의 손님이 운영자 몰을 거쳐 왔는가** — 유어딜 *자기영업*을 끄는 용도 전용 (2026-08-12).
 *
 * 왜 필요한가: 결제 완료 화면이 몰 손님에게도 *"내 쇼핑몰에서도 팔 수 있어요"* 를 띄우고 있었다.
 * 운영자가 카톡으로 데려온 손님에게 **유어딜이 셀러가 되라고 권하는** 화면이다 —
 * 브랜딩 문제가 아니라 **고객 가로채기**라, 대표가 세 번 요구한 "완전 별개"의 정면 위반이다.
 *
 * 🔴 **왜 여기서는 흔적을 써도 되는가**(위 "쓰지 말 것"과의 경계):
 *   판정 대상이 **상품이 아니라 "유어딜이 지금 영업을 해도 되는 자리인가"** 이고,
 *   틀렸을 때의 손해가 **한 방향으로만** 난다:
 *     - 거짓 양성(몰을 지나쳤을 뿐인 본진 구매) → 영업 배너 1회 미노출. **손해 거의 0.**
 *     - 거짓 음성(몰 손님인데 배너 노출)       → 운영자 손님을 유어딜이 데려간다. **관계가 깨진다.**
 *   비대칭이 명확하므로 **모르면 끄는 쪽**이 옳다. 상품·가격·결제 판정에는 여전히 쓰지 않는다.
 *
 * ⚠️ **한계(다음 세션용)**: 이건 클라 세션 신호라 정확하지 않다. 정확히 하려면 주문에 실린
 *   상품의 `mall_id`(서버 데이터)를 봐야 한다. 그 승격은 결제 완료 응답에 몰 정보를 싣는 작업이
 *   선행돼야 하고, 그 화면(`PaymentSuccessPage`)은 **Toss 감사 잠금**이라 대표 승인이 필요하다.
 */
export function isFromMallSession(): boolean {
  return readMallOrigin() != null
}
