/**
 * 칩·드롭다운에 찍는 이름.
 *
 * ⚠️ 원 표의 `label` 을 안 쓴다 — 거기엔 줄바꿈(`'충남\n세종'`)과 지역 병기(`'전주/전북'`)가
 * 들어 있는데 둘 다 **세로 사이드바용**이지 가로 알약용이 아니다. 칩에선 키가 곧 이름이고
 * 한 군데만 손본다.
 */
export function shortsRegionLabel(key: string | null | undefined): string {
  if (!key) return ''
  return key === '충남세종' ? '충남·세종' : key
}
