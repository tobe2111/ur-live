/**
 * 🧭 2026-10-12 — **시드가 없는 표면이 크롤러에게 줄 문장** SSOT.
 *
 * 대표 *"내 판단이 필요한 3가지 모두 가장 이상적으로 해줄 수 없어?"* 의 ②.
 *
 * ## 실측 (Googlebot UA 로 라이브, sitemap 제출 정적 경로 전수)
 *
 *     /join 15 · /terms 15 · /refund 17 · /creators/apply 20 · /privacy 21
 *     /influencer 28 · /creators 28 · /introduce 30 · /experience 33
 *     /area-report 36 · /partners 37 · /region 38          ← 전부 thin content
 *     (대조: 2026-10-12 에 고친 /faq 1,537자 · /about 288자)
 *
 * 전부 **sitemap 이 제출하는 URL** 이다. 즉 "색인해 달라" 고 선언해 놓고 20~40자를 주고 있었다.
 * 그 상태로는 *"유어딜 입점"*·*"체험단"*·*"동네 할인권 소개"* 질의에 인용할 문장이 한 줄도 없다.
 *
 * ## 왜 `<noscript>` 인가
 *
 * 이 표면들은 **재사용할 캐시 키가 없다**(목록 넷·지역과 달리 시드가 안 온다). 서버가 첫 화면을
 * 그리려면 **새 self-fetch** 가 필요하고 그건 2026-10-12 에 세운 규율(추가 요청 0)을 깬다.
 * 그런데 이 페이지들의 내용은 **데이터가 아니라 문구**다 — 조회할 것이 없다. 그래서 그 문구를
 * 여기 모아 서버가 바로 쓴다. JS 가 돌면 `<noscript>` 는 렌더조차 안 되므로 **사람 화면
 * byte-동일 · 밀림 0**(2026-10-12 `/faq`·`/about`·`/region` 과 같은 수법).
 *
 * ## 🔴 규율 — 두 벌을 만들지 않는다 (이 파일의 존재 이유)
 *
 * 아래 문장은 **지금 그 화면에 떠 있는 것과 같은 말이어야 한다.** 크롤러에게만 다른 소개를
 * 주는 것은 클로킹이고 구글이 명시적으로 금지한다. 그래서 각 항목이 `source`(그 문구가 사는
 * 페이지 파일)를 들고 있고, **가드가 각 줄이 그 파일 소스에 실재하는지 대조한다**(공백 정규화).
 * 페이지 문구를 고치면 가드가 빨간불이 되고, 그때 여기도 같이 고치게 된다.
 *
 * ⚠️ 그러니 **여기에 새 문장을 지어 쓰면 안 된다** — 화면에 없는 말은 가드가 막는다.
 *    새 문장이 필요하면 **화면에 먼저 쓰고** 그 문장을 여기로 옮긴다.
 *
 * ## 수치를 적지 않는다
 *
 * 요율·기간·금액은 어드민 조정 대상(`platform_settings`)이라 여기 적으면 반드시 낡는다.
 * 그래서 `{F.feeDirect}` 같은 보간이 섞인 줄은 **일부러 고르지 않았다**(그 줄은 페이지가 그린다).
 *
 * ## ⚠️ 이 파일이 안 하는 것
 *
 * - **법정 문서는 여기 없다.** `/terms`·`/terms/seller` 는 그 문서 자체(`TermsDoc`)의 **조항
 *   제목**을 `crawler-noscript.ts` 가 파생해 쓴다 — 손으로 요약하면 개정될 때 갈린다.
 * - **`/privacy`(21자)·`/refund`(17자)는 일부러 안 했다.** 그 둘은 본문이 **JSX 안에 박혀**
 *   있어(게다가 `/privacy` 는 국문·영문 분기) 문서에서 파생할 수가 없고, 손으로 요약을 쓰면
 *   **화면에 없는 말**이 되어 이 파일의 규율을 내가 깨는 셈이다. 올바른 수선은 그 둘도
 *   `TermsDoc` 같은 콘텐츠 SSOT 로 옮기는 것이고 **별건**이다(법정 문서라 문구 변경 = 대표 확인).
 * - 구글이 실제로 색인하는지(수일~수주 · 서치콘솔은 대표만 본다).
 */

