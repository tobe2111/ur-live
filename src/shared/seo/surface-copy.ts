/** 이 경로에 줄 문장이 있는가. */
export function surfaceCopyFor(pathname: string): SurfaceCopy | null {
  const path = pathname !== '/' && pathname.endsWith('/') ? pathname.slice(0, -1) : pathname
  return SURFACE_COPY[path] ?? null
}
