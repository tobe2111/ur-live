/**
 * ♻️ **여력 자동배치** — 한 트랙이 마르면 그 회차의 남은 예산을 다음 트랙이 자동으로 가져간다.
 *
 * ## 왜 필요한가 (2026-08-12 대표 지시 *"이런 설정도 자동으로 알아서 소진하게끔 해줘 여력 자동배치"*)
 * 측정 샤드 4개 중 1~3번은 **블로그 전용**(`naverOnly`)이다. 블로그 백로그가 비면 그 셋은
 * `enrichNaverActivity` 가 0행을 고르고 **그대로 회차를 끝낸다** — 예산은 남는데 아무 일도 안 한다.
 * 라이브 실측(08-12 20:35)이 바로 그 직전이었다:
 * ```
 *   블로그 1,423 (순감 시간당 −690 → 2시간 뒤 0)   ← 곧 마름
 *   유튜브   667 (이메일 수율 36.3% — 가장 높다)   ← 남아 있는데 손을 못 댐
 *   측정 능력 22,605/일  vs  유입 6,435/일 = 3.5배
 * ```
 * ⇒ 블로그가 비는 순간 **샤드 3개가 통째로 유휴**가 된다. 사람이 그때 설정을 바꿔 주지 않으면
 *   능력의 3분의 2가 그냥 논다. 그걸 사람 손에 맡기지 않는 것이 이 파일의 목적이다.
 *
 * ## 규칙 — "고를 게 없었나"로만 판단한다
 * 되돌아갈 근거는 **`selected === 0`**(그 슬라이스에서 **자격 있는 행을 하나도 못 찾음**)뿐이다.
 * `measured === 0` 으로 판단하면 안 된다 — 그건 "큐가 빔"과 "예산/시계가 먼저 끊김"을 구분 못 해
 * 바쁠 때 오히려 트랙을 갈아타 버린다(이 레포가 반복해 만난 *"실패와 부재를 같은 값으로 뭉개는"* 클래스).
 * 이 구분은 `influencer-performance.ts:154` 주석이 명시적으로 지키고 있는 성질이라 신뢰할 수 있다.
 *
 * ⚠️ **남은 예산이 실제로 쓸 만큼 있어야 한다** — 폴백 자체가 서브리퀘스트를 쓴다(bio 1/행, YT 1/행+배치 1).
 *   바닥 근처에서 갈아타면 아무것도 못 하고 다음 회차의 몫만 태운다.
 * ⚠️ **YT 쿼터는 이 함수가 안 본다.** 그건 `ytRoom`(일일 units 카운터)이 이미 막고 있고, 여기서 또 보면
 *   같은 규칙이 두 벌이 되어 조용히 갈라진다. 이 함수는 *"갈아탈 자격이 되는가"* 만 판정한다.
 * ⚠️ 카페(3,146명)는 **아직 대상이 아니다** — 보강 함수 자체가 없고 한 번도 측정된 적이 없다
 *   (`admin-ads-influencers.routes.ts:70` 이 기본 목록에서 숨기는 별도 취급 축). 트랙이 생기면
 *   이 함수의 판정만 재사용하면 된다 — 그게 여기 순수함수로 떼어 둔 이유다.
 */

/** 폴백 판정 입력 — 전부 이미 계산돼 있는 값이다(새로 재지 않는다). */
export interface FallbackInput {
  /** 그 트랙이 이 회차에 **고른** 행 수. `undefined` 면 트랙이 아예 안 돌았다는 뜻이라 판정하지 않는다. */
  selected?: number
  /** 남은 서브리퀘스트 예산. */
  budgetLeft: number
}

/**
 * 남은 예산을 **링크인바이오**로 넘길 것인가.
 *
 * ⚠️ **유튜브가 아니라 링크인바이오인 이유**: 샤드 4개가 각자 일일 units 카운터를 읽고 쓰므로
 *   동시에 YT 를 부르면 **쿼터가 곱해진다**(그 불변식은 `ads-enrich-shards` 테스트가 지키고 있고,
 *   실제로 이 수리의 첫 판이 그 테스트에 걸렸다). 링크인바이오는 3자 쿼터가 없고 이메일을 직접
 *   만들어 내므로 — 이 DB 의 유일한 성공 지표 — 남는 예산의 행선지로 정확히 맞다.
 *
 * 최소 예산 4 = 링크인바이오 1행(1) + SELECT/쓰기(2) + 여유 1. 이보다 적으면 갈아타 봐야
 * 한 행도 못 끝내고 다음 회차 몫만 축낸다.
 */
export const FALLBACK_MIN_BUDGET = 4

export function shouldFallbackToFront(i: FallbackInput, minBudget = FALLBACK_MIN_BUDGET): boolean {
  if (i.selected === undefined || !Number.isFinite(i.selected)) return false  // 트랙이 안 돌았다 = 무판정
  if (i.selected > 0) return false                                            // 할 일이 있었다
  const left = Number.isFinite(i.budgetLeft) ? i.budgetLeft : 0
  return left >= Math.max(1, minBudget)
}
