/**
 * 🔄 **에폭(최근 창) 은퇴** — 기존 은퇴 3조건의 공통 사각지대를 닫는다 (2026-08-17 실측으로 신설).
 *
 * ## 무엇이 고장이었나
 * 기존 은퇴 3조건(`f30`·`barren`·`yield`)은 전부 **평생 누계** 기준이다. 그래서 *초기에 잘 나갔던*
 * 키워드는 지금 말라붙어도 **영구 면역**을 얻는다. 라이브 실측:
 *
 * ```
 * 활성 auto 120개 중 은퇴 후보 = 0개      ← "밀린 게 없다"가 아니라 "필터가 이 부류를 못 본다"
 * 맛집      871회 / 591건  → 회당 0.68     saved_total 591 ≥ 10 이라 yield 조건 면제
 * 여행      288회 / 746건  → 회당 2.59     barren_streak 0 (가끔 물어 리셋)
 * 피부관리  453회 / 561건  → 회당 1.24
 * 대기 후보 기대 수확       → 회당 23.6    ← 8~35배 손해를 보며 슬롯이 잠겨 있었다
 * ```
 *
 * 🩸 2026-08-12 세션은 같은 "후보 0" 을 보고 *"은퇴가 안 돌아 막혔다는 진단은 **틀렸다**"* 고 적었다.
 *   숫자는 맞았고 해석이 뒤집혔다 — **0 은 건강의 증거가 아니라 필터가 눈이 멀었다는 증거**였다.
 *
 * ## 왜 평생 평균으로 자르면 안 되는가
 * '인테리어'(170회/500건 = 회당 2.94)는 **직전 회차에 35건**을 물었다. 평생 평균으로 자르면 이런
 * *회복 중인* 키워드를 죽인다. 과거가 아니라 **지금**을 재야 하고, 그게 에폭이다.
 *
 * ## 자가치유 — 영구 배제가 아니다 (대표 확정 2026-08-09 *"영구 배제가 되면 안된다"*)
 * 에폭은 **승격 시 리셋**된다. 그래서 재승격자는 백지에서 8회를 새로 받는다 — 평생 카운터와 달리
 * "되살리면 즉시 재은퇴" 하는 livelock 구조가 성립하지 않는다. 그래서 `PROMOTE_NOT_RETIRABLE_SQL`
 * 에는 **넣지 않는다**(넣으면 자가치유가 막혀 30일 영구 배제가 된다). 대신 churn 만 쿨다운으로 막는다.
 */

/**
 * 판단 근거: 대기 후보의 기대 수확이 **회당 23.6건**이라 회당 2건 미만이면 **교체가 10배 이득**이다.
 * 8회는 "우연히 마른 두어 회차"와 "진짜 고갈"을 가르는 최소 표본 — 편식 순환상 마른 키워드일수록
 * 자주 뽑혀 며칠이면 채운다. 보수적으로 잡았다(올리면 회전이 빨라지지만 회복 중인 키워드를 자를 위험이 커진다).
 * ⚠️ 재조정 전에 라이브 은퇴/승격 추이를 먼저 볼 것 — 이 두 수는 **실측 없이 만지면 안 된다.**
 */
export const EPOCH_MIN_RUNS = 8
export const EPOCH_MIN_YIELD = 2.0
/** 🕊️ 에폭 은퇴자의 재승격 쿨다운(일). 자가치유라 영구 차단은 아니고 즉시 재승격 churn 만 막는다. */
export const RETIRE_COOLDOWN_DAYS = 14

/**
 * 에폭 은퇴 WHERE 조각. `freshEvidence` 는 rotation 의 증거 유통기한 조각을 그대로 받는다
 * (두 벌로 두면 은퇴 기준이 조용히 갈린다).
 *
 * ⚠️ 분모에 `COALESCE(epoch_runs, 1)` — 0 나눗셈 방지용이고, 앞선 `>= EPOCH_MIN_RUNS` 가 이미
 *   0 을 걸러내므로 판정에는 영향이 없다.
 */
export const buildEpochRetireSql = (freshEvidence: string): string =>
  `COALESCE(epoch_runs, 0) >= ${EPOCH_MIN_RUNS}`
  + ` AND COALESCE(epoch_saved, 0) * 1.0 / COALESCE(epoch_runs, 1) < ${EPOCH_MIN_YIELD}`
  + ` AND ${freshEvidence}`

/**
 * 🚫 **승격 쿨다운** — `hits DESC` 정렬이라 옛 활성 키워드가 대기 큐를 제칠 수 있다. 이게 없으면
 *   같은 키워드가 "승격 → 8회 시험 → 은퇴" 를 반복하며 슬롯을 태운다(대기 11,720개가 밖에 있는데).
 */
export const PROMOTE_COOLDOWN_SQL =
  `(retired_at IS NULL OR retired_at <= datetime('now','-${RETIRE_COOLDOWN_DAYS} days'))`
