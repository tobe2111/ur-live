/**
 * 🪪 **`마케터` 는 이름에서만 업(業) 신호다** (2026-08-03 라이브 실측).
 *
 * ## 무엇이 문제였나
 * 대행사 규칙은 자기 주석에 함정 넷을 적어 놓고 *"업 신호를 요구한다"* 고 선언했는데,
 * 정작 마지막 토큰 `마케터` 만 맨몸으로 남아 있었다. 라이브에서 실제로 밟혔다 —
 * 대행사로 분류된 **273명 중 45명(16%)이 오직 이 단어 하나로** 들어왔다:
 *
 * ```
 *   와그잡의 트래블홀릭  "…여행 인플루언서 & 일본 전문 마케터 와그잡"   ← 여행 블로거
 *   럭키뚜래블          "75개국 여행한 디지털 노마드. 15년차 마케터"    ← 여행 블로거
 *   글수저              (제주 흑돼지 맛집 글)                          ← 맛집 블로거
 * ```
 *
 * 단순한 오분류가 아니라 **도둑질**이다 — 그 45명의 원래 자리는
 * 맛집 10 · 외식창업 8 · IT/재테크 5 · 카페 5 · 숙소 4 · 여행 2 · 패션 1 · 미분류 10 으로,
 * 대부분 **유어딜 이용권 본체 축**이다. 그리고 대표가 대행사 목록으로 제휴 제안을 보내면
 * 6명 중 1명은 대행사가 아닌 사람이 받는다.
 *
 * ## 갈림이 왜 이름/소개글인가
 * 실측 45건의 분포가 깨끗했다. **이름 14건은 전부 자기 정체성 선언**(싱어송마케터 · 지역전문마케터 ·
 * 로컬마케터즈 · QR마케터 · 디지털마케터 디노), **소개글 31건은 전부 지나온 경력이나 곁가지 언급**.
 * 자기를 그렇게 부르는 것과 이력에 한 줄 적는 것은 다른 신호다.
 *
 * ⚠️ 이 테스트가 **못 보는 것**: 이름에 `마케터` 를 넣고도 실제로는 대행을 안 하는 사람
 * (예: 개인 브랜딩). 그건 문자열로 판정할 수 없고, 리드 품질은 사람이 볼 몫이다.
 * ⚠️ 라이브 재분류 결과 예측치(아래 숫자)는 **주석의 기록**이지 검사가 아니다 — 풀은 계속 변한다.
 */
import { describe, it, expect } from 'vitest'
import { classifyCategory, shouldClearCategory } from '@/features/marketing/api/influencer-classify'

describe('마케터 — 이름에서만 대행사 신호', () => {
  it('🔒 이름에 있으면 대행사다 — 자기 정체성 선언', () => {
    for (const n of ['싱어송마케터', '지역전문마케터', '로컬마케터즈', 'QR마케터', '디지털마케터 디노', '구멍가게마케터박철홍']) {
      expect(classifyCategory(n, '일상 이야기를 씁니다'), n).toBe('마케팅대행사')
    }
  })

  it('🔒 소개글에만 있으면 대행사가 아니다 — 지나온 경력·곁가지 언급', () => {
    // 라이브 실물(설명은 축약). 셋 다 원래 자리로 돌아가야 한다.
    expect(classifyCategory('와그잡의 트래블홀릭', '여행 인플루언서 & 일본 전문 마케터 와그잡. 인천 호캉스 후기'))
      .not.toBe('마케팅대행사')
    expect(classifyCategory('럭키뚜래블', '75개국을 여행한 8년차 디지털 노마드. 15년차 마케터. 경주 황리단길 숙소 후기'))
      .not.toBe('마케팅대행사')
    expect(classifyCategory('멜로우의 꿀테크 라이프', '건설, 호텔, IoT 10년차 인하우스 마케터. 제주 맛집 투어'))
      .not.toBe('마케팅대행사')
  })

  it('🔒 훔쳐온 자리를 실제로 돌려준다 — "안 걸린다"가 아니라 "제 축으로 간다"', () => {
    expect(classifyCategory('럭키뚜래블', '15년차 마케터. 경주 황리단길 한옥 스테이 숙소 후기')).toBe('숙소')
    expect(classifyCategory('글수저', '인하우스 마케터 출신. 제주 한림 흑돼지 로컬 맛집 잉겅')).toBe('맛집')
  })

  it('🔒 지망생은 대행사가 아니다 — bare 마케팅이 학생·구직을 끌고 오던 그 함정', () => {
    expect(classifyCategory('마케터 지망생', '취업 준비 기록')).not.toBe('마케팅대행사')
  })

  it('🔒 진짜 업 신호는 소개글에 있어도 그대로 잡는다 — 좁히기가 과했는지 확인', () => {
    for (const d of ['블로그 마케팅 대행사입니다', '체험단 모집 및 운영 대행', '인플루언서 섭외 문의 주세요', '퍼포먼스 마케팅 · 광고 집행']) {
      expect(classifyCategory('어떤 채널', d), d).toBe('마케팅대행사')
    }
  })

  /**
   * 규칙을 좁히면 `classifyCategory` 가 `null` 을 주는 행이 생기는데, 재분류는 **null 이면 그대로
   * 둔다**. 그러면 옛 값이 영구히 굳는다(`shouldClearCategory` docblock 이 실측으로 경고한 그대로).
   * 라이브 45건 중 10건이 정확히 그 경우였다 → 비워서 키워드 상속·재보정이 다시 채우게 한다.
   */
  it('🔒 어느 규칙에도 안 걸리면 옛 대행사 값을 비운다 — 안 그러면 영구히 굳는다', () => {
    expect(shouldClearCategory('마케팅대행사', '어떤 블로그', '10년차 마케터의 소소한 일상')).toBe(true)
  })

  it('🔒 아직 대행사가 맞는 행은 안 비운다 — 비우기가 과하면 멀쩡한 분류가 날아간다', () => {
    expect(shouldClearCategory('마케팅대행사', 'QR마케터', '일상')).toBe(false)
    expect(shouldClearCategory('마케팅대행사', '어떤 채널', '체험단 모집 대행합니다')).toBe(false)
  })

  it('🔒 비우기는 대행사에만 적용된다 — 일반화하면 키워드 상속 분류까지 날아간다', () => {
    expect(shouldClearCategory('맛집', '어떤 블로그', '오늘 날씨가 좋네요')).toBe(false)
    expect(shouldClearCategory('숙소', '어떤 블로그', '오늘 날씨가 좋네요')).toBe(false)
  })
})
