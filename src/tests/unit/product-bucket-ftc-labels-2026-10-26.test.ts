/**
 * 🏷️ 공정위 품목 라벨 11종이 **전부 제 버킷으로** 간다 (2026-10-26).
 *
 * 왜 생겼나 — 라이브 `ad_company_leads.description` 의 한글 품목 **1,393건을 전수로** 세니
 * 어휘가 **닫힌 11종**이었고(공정위 통신판매 신고 표준), 그중 **둘이 엉뚱한 버킷**으로 갔다:
 *
 *     컴퓨터/사무용품 → 도서·문구   (그 정규식의 `사무용품` 이 2번째라 `컴퓨터` 를 가로챘다)  라이브 45행
 *     가구/수납용품   → 생활·주방   (그 정규식의 `수납` 이 7번째라 `가구` 를 가로챘다)      라이브 28행
 *
 * 🔴 **이미 찍힌 라벨은 코드 수리로 안 지워진다** — `ON CONFLICT` 는 총칭(`통신판매`)만 승격하고
 * 구체 라벨은 보존한다. 그래서 그 73행은 데이터 UPDATE(결재) 대상이고, 이 수리가 하는 일은
 * **그 뒤로 더 안 늘게** 막는 것이다. ⇒ 놓치면 조용히 계속 쌓이는 클래스라 가드가 필요하다.
 *
 * 🧷 판정은 **진짜 `productBucket` 을 돌려서** 한다(소스 문자열 검사가 아니다) — 표의 *순서*가
 * 결과를 정하는데 순서는 문자열로 못 본다. 그게 이 결함의 정체이기도 하다.
 *
 * ⚠️ **이 시험이 못 보는 것**: 11종 밖의 자유 텍스트(블로그·크롤 문구) 분류가 좋은가 ·
 * 숫자 코드(`취급 12`)의 뜻(코드표는 2026-10-25 결재에서 **기각**됐다 — 대표께 다시 묻지 말 것) ·
 * 라이브에 이미 찍힌 73행(데이터이지 코드가 아니다).
 */
import { describe, it, expect } from 'vitest'
import { productBucket } from '@/features/marketing/api/commerce-notify-collect'
import { readCode } from '../helpers/source-text'

const SRC = 'src/features/marketing/api/commerce-notify-collect.ts'

/** 🔢 공정위 품목 라벨 11종 → 기대 버킷. **실측한 문자열만** 적는다(표준 목록을 기억으로 쓰지 않는다). */
const FTC_LABELS: Array<[string, string | null]> = [
  ['종합몰', '종합몰'],
  ['의류/패션/잡화/뷰티', '패션·잡화'],
  ['건강/식품', '식품'],
  ['교육/도서/완구/오락', '도서·문구'],
  ['레저/여행/공연', '스포츠·레저'],
  ['가구/수납용품', '가구·인테리어'],
  ['컴퓨터/사무용품', '가전·디지털'],
  ['자동차/자동차용품', '자동차·공구'],
  ['가전', '가전·디지털'],
  // 🔴 둘은 **일부러 버킷이 없다** — `성인/성인용품`(11행)은 B2B 마케팅 풀에 둘 라벨이 아니고,
  //   `기타` 는 공정위 자신의 '기타' 라 우리가 뜻을 지어낼 수 없다. 둘 다 `통신판매` 로 남는다.
  ['성인/성인용품', null],
  ['기타', null],
]

describe('① 공정위 11종이 전부 제 버킷으로 간다', () => {
  for (const [label, want] of FTC_LABELS) {
    it(`${label} → ${want ?? '(없음 → 통신판매)'}`, () => {
      expect(productBucket(label)).toBe(want)
    })
  }
  it('측정 대상이 비면 통과가 아니다', () => {
    expect(FTC_LABELS.length).toBe(11)
    expect(FTC_LABELS.filter(([, w]) => w !== null).length).toBe(9)
  })
})

describe('② 라이브에서 실제로 본 복합 라벨 — 종합몰이 맨 앞을 지킨다', () => {
  // 실측 세그먼트(상위): 공정위는 신고 품목을 공백으로 이어 준다.
  it('종합몰 + 다른 품목이면 종합몰(최상위 포괄)', () => {
    expect(productBucket('종합몰 의류/패션/잡화/뷰티')).toBe('종합몰')
    expect(productBucket('종합몰 건강/식품')).toBe('종합몰')
    expect(productBucket('종합몰 가구/수납용품')).toBe('종합몰')
    expect(productBucket('의류/패션/잡화/뷰티 종합몰')).toBe('종합몰')
  })
  it('기타가 섞여도 구체 품목이 이긴다', () => {
    expect(productBucket('기타 의류/패션/잡화/뷰티')).toBe('패션·잡화')
    expect(productBucket('건강/식품 기타')).toBe('식품')
  })
  it('2026-10-25 에 고친 것이 되돌아오지 않는다 — 완구가 교육·도서를 가로채지 않는다', () => {
    expect(productBucket('종합몰 교육/도서/완구/오락')).toBe('종합몰')
    expect(productBucket('교육/도서/완구/오락')).toBe('도서·문구')
  })
})

describe('③ 앵커는 슬래시째 리터럴 — 자유 텍스트를 끌어오지 않는다', () => {
  // 🧷 `컴퓨터`·`가구` 를 **낱말**로 올리면 블로그·크롤 문구가 함께 끌려온다. 공정위 라벨에서만
  //   나오는 슬래시 리터럴로 앵커했는지를 **동작으로** 확인한다.
  it('도서 위주 자유 텍스트는 여전히 도서·문구', () => {
    expect(productBucket('컴퓨터 서적 · 프로그래밍 도서 전문')).toBe('도서·문구')
  })
  it('수납 위주 자유 텍스트는 여전히 생활·주방', () => {
    expect(productBucket('주방 수납 정리용품')).toBe('생활·주방')
  })
  it('소스의 두 규칙이 리터럴 앵커를 쓴다', () => {
    const s = readCode(SRC)
    expect(s).toMatch(/\['가전·디지털', \/컴퓨터\\\/사무용품\//)
    expect(s).toMatch(/\['가구·인테리어', \/가구\\\/수납용품\//)
  })
})
