import { describe, it, expect } from 'vitest'
import { classifyCategory } from '@/features/marketing/api/influencer-classify'
import { PRIORITY_CATEGORIES } from '@/features/marketing/api/influencer-keyword-rotation'

/**
 * 🛒 2026-07-29 공동구매/라이브공구 축 신설(대표 지시)의 불변식 잠금.
 *
 *   왜 이 축인가: 이미 **자기 팔로워에게 직접 파는** 사람들이라 유어샵(내 쇼핑몰) 전환 장벽이 사실상 0.
 *   리뷰만 하던 사람은 '판매'라는 새 행위를 배워야 하지만 공구 셀러는 이미 그걸 하고 있다.
 *
 *   ⚠️ 이 축의 진짜 위험은 **동음이의어**다. 한국어 '공구'는 工具(전동공구·공구상가·공구함)와 겹쳐서,
 *   맨 단어로 매칭하면 하드웨어 리뷰어가 공구 셀러로 대량 유입된다. 한 번 잘못 들어오면 사람이
 *   발송 큐에서 걸러야 하고(= 이 세션이 줄이려는 바로 그 시간), 카테고리 통계도 오염된다.
 *   그래서 규칙은 **공동구매 문맥이 붙은 형태만** 잡는다.
 */
describe('공동구매 분류 — 동음이의어(工具) 오탐 차단', () => {
  it('① 공동구매 셀러를 잡는다', () => {
    for (const s of [
      '공동구매 진행합니다', '이번주 공구 오픈!', '공구 진행중이에요', '인스타 공구 전문',
      '블로그 공구 후기', '맘카페 공구 링크', '쇼핑라이브 진행', '라이브커머스 크리에이터',
      '그립 라이브 방송', '공구 마감 임박', '공구 셀러입니다',
      // 확장분(2026-07-29) — 유통 경로·품목·프로모션 문맥
      '공구템 소개', '맘공구 진행해요', '밴드 공구 안내', '카톡 공구 오픈', '오픈채팅 공구',
      '라방 공구 합니다', '최저가 공구', '특가 공구 소식', '한정 공구',
      '뷰티 공구 진행', '반찬 공구', '육아용품 공구', '공구 진행자입니다', '네이버 쇼핑라이브 출연',
    ]) {
      expect(classifyCategory(s, null), `"${s}"`).toBe('공동구매')
    }
  })

  it('② 工具(하드웨어)는 절대 공동구매로 분류하지 않는다', () => {
    for (const s of [
      '전동공구 리뷰', '공구상가 탐방', '공구함 정리', '목공 공구 추천',
      '자동차 정비 공구', '공구 브랜드 비교', 'DIY 공구 세트',
      // 확장하다 실제로 뚫렸던 자리 — `공구\s*중` 이 '중고'를 삼켰다(工具 중고거래).
      '공구 중고거래', '공구 중고 판매', '전동공구 중고',
    ]) {
      expect(classifyCategory(s, null), `"${s}"`).not.toBe('공동구매')
    }
  })

  it('③ bare 라방은 커머스 신호가 아니다(게임·소통 방송이 더 흔하다)', () => {
    expect(classifyCategory('오늘 라방 켭니다', null)).not.toBe('공동구매')
    expect(classifyCategory('라방 하는 게임 스트리머', null)).not.toBe('공동구매')
  })

  it('④ 행위(판매)가 주제(뷰티)보다 먼저 — 뷰티 공구는 공동구매로 잡힌다', () => {
    expect(classifyCategory('뷰티 공구 오픈합니다', null)).toBe('공동구매')
    // 판매 신호가 없으면 원래 주제 그대로(축 추가가 기존 분류를 삼키지 않는다)
    expect(classifyCategory('메이크업 튜토리얼 채널', null)).toBe('뷰티')
    expect(classifyCategory('네일아트 디자인', null)).toBe('네일')
  })

  it('⑤ 우선풀에 포함된다 — 아니면 희소한 YT 검색 슬롯이 이 축에 안 간다', () => {
    expect(PRIORITY_CATEGORIES).toContain('공동구매')
  })
})
