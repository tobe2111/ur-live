export const SECONDS_PER_INJECTION = 2.5

/**
 * 조각 하나의 목표 벽시계(분). 작게 잡는 이유는 둘이다 —
 * ① 러너 손실 시 잃는 것이 그만큼뿐 ② 야간 전체가 이 값 + 설치시간 안에 끝난다.
 * ⚠️ 조각마다 `checkout + setup-node + npm ci` 고정비가 붙는다 — **실측 ~0.6분**
 *    (checkout 11~17s + node 3~9s + npm ci 7~16s. npm 캐시가 살아 있어 생각보다 싸다).
 *    🩸 2026-10-01 에 이 자리에 `~2분` 이라고 적어 뒀는데 **3배 틀린 값**이었고, 그 과대값이
 *    `SECONDS_PER_INJECTION` 의 과소값(3.4 vs 실측 3.79)과 상쇄돼 추정이 '정확히 맞는' 것처럼
 *    보였다. 두 틀린 값이 맞는 답을 낸 것이라, 하나만 고치면 그때 어긋난다.
 */
export const TARGET_SHARD_MINUTES = 12

/**
 * 조각 수 상한. 폭주한 주입 수가 러너를 100개 띄우는 것을 막는다.
 * 이 상한에 닿으면 조각이 아니라 **주입 자체의 비용**을 봐야 한다는 신호다.
 */
export const MAX_SHARDS = 16

/**
 * 주입 수 → 조각 계획. 순수 함수(테스트가 문자열이 아니라 **동작**을 잰다).
 * @param {number} count 전체 주입 수
 * @returns {{ total: number, perShard: number, estMinutes: number }}
 */
export function planShards(count) {
  if (!Number.isFinite(count) || count < 0) throw new Error(`planShards: 주입 수가 숫자가 아니다 — ${count}`)
  const totalMinutes = (count * SECONDS_PER_INJECTION) / 60
  const want = Math.ceil(totalMinutes / TARGET_SHARD_MINUTES)
  // 0건이어도 조각 1개는 돈다 — 그 1개가 "0건이면 실패" 를 보고하는 자리다.
  const total = Math.min(MAX_SHARDS, Math.max(1, want))
  const perShard = Math.ceil(count / total)
  return { total, perShard, estMinutes: (perShard * SECONDS_PER_INJECTION) / 60 }
}

/**
 * 🧮 **주입을 조각에 배분한다 — 테스트 파일 단위로 묶어서.**
 *
 * ## 왜 색인 나머지(`i % n`)를 버렸나 (2026-10-01 실측)
 * 러너는 주입 하나를 검증할 때 `npx vitest run <그 주입의 테스트>` 를 돌리고, **그 전에**
 * 같은 테스트의 baseline("주입 전에도 초록인가")을 한 번 돈다(`baselineCache`, 테스트 파일별 1회).
 * ⇒ 한 조각의 실제 비용은 주입 수가 아니라 **vitest 호출 수 = 주입 수 + 그 조각이 건드린 고유 테스트 수**다.
 *
 * `i % n` 은 같은 테스트를 쓰는 주입을 **모든 조각에 흩뿌린다.** 그래서 baseline 이 조각마다
 * 다시 돌아 **중복**된다. 실측(주입 2,411 · 고유 테스트 519):
 * ```
 *   한 덩어리 전수   호출 2,930 = baseline  519 + 주입 2,411   → 1.22 호출/주입
 *   i % 12          호출 4,652 (최대 조각 396)                → 1.97 호출/주입  ← baseline 을 12번
 *   그룹 LPT(12)     호출 2,930 (최대 조각 245)                → 1.21 호출/주입  ← 중복 0
 * ```
 * **최대 조각이 38% 줄고**, 조각을 늘릴 때의 수익이 다시 선형이 된다 — 종전엔 조각을 늘릴수록
 * baseline 중복이 함께 늘어 **수익이 체감**했다(실측: 현행 9→24조각 508→202 호출 vs 그룹 326→123).
 *
 * ## 어떻게
 * 테스트 파일로 묶고, **큰 그룹 먼저**(LPT) 지금 가장 싼 조각에 넣는다. 비용은 `주입 수 + 1`
 * (그 조각에 그 테스트의 baseline 이 한 번 생긴다). 동률은 번호·키 사전순 — **결정론**이라
 * 같은 매니페스트면 어느 러너에서 몇 번 돌려도 같은 배분이 나온다(조각들이 서로를 신뢰하는 근거).
 *
 * ## ⚠️ 주입 수 균형은 **덤이지 보장이 아니다**
 * 비용으로 묶으므로 주입 수는 완벽히 같지 않다. LPT 성질상 편차는 **가장 큰 그룹 크기**로 묶이고,
 * 실측에서 최대 그룹이 30건(조각당 201건의 15%)이라 결과는 200~202 로 거의 같다.
 * 한 테스트에 주입이 수백 개 쌓이면 그 그룹이 조각 하나를 혼자 정하므로, 그때는 **그 테스트를 쪼개는** 것이
 * 답이다(테스트가 그 신호를 빨간불로 낸다).
 *
 * @param {{ name?: string, test?: string }[]} items 주입 목록(러너의 `ALL` 순서 그대로)
 * @param {number} total 조각 수
 * @returns {number[]} `items` 와 같은 길이·순서의 조각 번호
 */
export function assignShards(items, total) {
  if (!Array.isArray(items)) throw new Error('assignShards: items 가 배열이 아니다')
  if (!Number.isInteger(total) || total < 1) throw new Error(`assignShards: total 이 1 이상 정수가 아니다 — ${total}`)

  // 🔑 테스트 경로가 그룹 키다. 없는 주입은 **홀로 선다**(한 그룹으로 뭉치면 그 조각만 비대해진다).
  const keyOf = (m, i) => (typeof m?.test === 'string' && m.test ? m.test : `\u0000no-test:${i}`)
  const groups = new Map()
  items.forEach((m, i) => {
    const k = keyOf(m, i)
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(i)
  })

  // 큰 그룹 먼저 — LPT. 같은 크기면 키 사전순(결정론).
  const ordered = [...groups.entries()].sort((a, b) => b[1].length - a[1].length || (a[0] < b[0] ? -1 : 1))

  const cost = Array.from({ length: total }, () => 0)
  const out = new Array(items.length)
  for (const [, idxs] of ordered) {
    let pick = 0
    for (let k = 1; k < total; k += 1) if (cost[k] < cost[pick]) pick = k   // 동률이면 작은 번호
    cost[pick] += idxs.length + 1   // 주입 N건 + baseline 1건 = vitest 호출 수
    for (const i of idxs) out[i] = pick
  }
  return out
}

/**
 * `--shard k/n` 파싱. 없으면 null(=전수).
 * @param {string[]} argv
 * @returns {{ index: number, total: number } | null}
 */
export function parseShard(argv) {
  const eq = argv.find((a) => a.startsWith('--shard='))
  const i = argv.indexOf('--shard')
  const raw = eq ? eq.slice('--shard='.length) : i !== -1 ? argv[i + 1] : null
  if (!raw) return null
  const m = /^(\d+)\/(\d+)$/.exec(raw.trim())
  if (!m) throw new Error(`--shard 는 \`k/n\` 형태다 (0 ≤ k < n) — 받은 값: ${raw}`)
  const index = Number(m[1])
  const total = Number(m[2])
  if (total < 1) throw new Error(`--shard: n 은 1 이상이어야 한다 — ${raw}`)
  if (index >= total) throw new Error(`--shard: k 는 n 보다 작아야 한다 — ${raw}`)
  return { index, total }
}

/**
 * 🖨️ `--plan <주입수>` — GitHub Actions 출력 형태로 계획을 찍는다.
 * 행렬을 사람이 적지 않게 하는 자리. 주입 수는 호출부(`--dump-manifest`)가 센 값을 넘긴다.
 */
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop() ?? '')) {
  const pi = process.argv.indexOf('--plan')
  if (pi !== -1) {
    const count = Number(process.argv[pi + 1])
    const { total, perShard, estMinutes } = planShards(count)
    const matrix = JSON.stringify([...Array(total).keys()])
    process.stdout.write(`matrix=${matrix}\ntotal=${total}\n`)
    process.stderr.write(
      `🧩 주입 ${count}건 → 조각 ${total}개 × 약 ${perShard}건 (조각당 추정 ${estMinutes.toFixed(1)}분, ` +
        `목표 ${TARGET_SHARD_MINUTES}분 · 상한 ${MAX_SHARDS}조각)\n`,
    )
  }
}
