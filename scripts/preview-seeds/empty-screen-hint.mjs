/**
 * 🟡 **"이 화면은 잴 내용이 있었는가"** — `--phone-audit` 의 판정 보류 규칙 (2026-10-01 분리).
 *
 * ## 왜 모듈로 뺐나
 * 이 규칙은 `visual-preview.mjs` 안의 정규식 **한 줄**이었고, 그래서 아무도 그 줄이 무엇을
 * 잡는지 재 본 적이 없다. 실측해 보니 **거짓 🟡 를 내고 있었다**:
 * ```
 *   /seller/settlements  →  "별도의 정산 신청은 필요 없습니다."  ← 안내 문장
 *   옛 규칙의 맨 `없습니다` 가 여기 걸려 🟡 "판정 보류"
 * ```
 * 그 화면은 가로스크롤 0 · 잘린 글자 0 · 콘솔 진짜 예외 0 · `/api` 20건 전부 응답으로
 * **끝까지 그려지는 화면**이었다. 결재문(`2026-09-28-my-stage2-sheet-teardown.md`)이
 * *"가장 중요한 화면(정산·출금)을 아직 못 쟀다"* 며 판단을 열어 둔 그 자리가, 사실은
 * **다 재고 있었는데 판정만 틀린 것**이었다.
 *
 * 🧭 이건 "헛도는 가드"(결함을 심어도 통과)의 **반대 방향**인데 해악은 같다 —
 *    🟡 가 상시 켜지면 아무도 🟡 를 안 읽는다. 신호가 신호 구실을 못 한다.
 *
 * ## 규칙의 핵심 — **조사(이/가)가 가른다**
 * 한국어 빈 상태는 *명사 + 이/가 + 없습니다* 다:
 *   `협업 deal 이 없습니다` · `등록된 이용권이 없습니다` · `정산 내역이 없습니다`
 * 안내 문장은 *부사 + 없습니다* 라 조사가 없다:
 *   `필요 없습니다` · `추가 서류는 필요 없습니다`
 * ⇒ 맨 `없습니다` 대신 `[이가]\s*없습니다` 를 본다. 세 화면 실측으로 검증했다(테스트에 픽스처로 박아 뒀다).
 *
 * ## 이 규칙이 **못 하는 것**
 * - 본문이 멀쩡한데 **일부 블록만** 빈 경우는 구분하지 못한다(전체가 🟡 가 된다). 그건 과한 쪽이라 둔다.
 * - 영어·다른 언어 빈 상태는 안 본다(이 하네스는 한국어 화면만 잰다).
 * - **"쓸 만한가"는 판정하지 않는다** — 잴 내용이 있었는지만 본다. 쓸 만한지는 숫자(가로스크롤·
 *   잘린 글자·작은 타깃)가 말한다.
 */

/**
 * 빈 상태·오류 화면의 **말투**. 맨 `없습니다` 금지 — 안내 문장(`필요 없습니다`)에 걸린다.
 */
export const EMPTY_HINT = /없어요|아직 .*없|[이가]\s*없습니다|비어 ?있|문제가 발생|오류가 발생|불러오지 못/

/**
 * 🔎 **무엇 때문에 🟡 인지** 돌려준다 — 판정만 보여 주면 고칠 수가 없다.
 *   (이 함수가 없던 탓에 "정산 화면이 왜 🟡 인가" 를 알아내는 데 렌더를 여러 번 돌렸다.)
 * @param {string} bodyText
 * @returns {string} 걸린 자리의 앞뒤 조각. 안 걸렸으면 빈 문자열.
 */
export function emptyHintMatch(bodyText) {
  const m = EMPTY_HINT.exec(bodyText ?? '')
  if (!m) return ''
  const i = m.index
  return (bodyText ?? '').slice(Math.max(0, i - 24), i + m[0].length + 8).replace(/\s+/g, ' ')
}

/**
 * @param {string} bodyText 화면 본문 텍스트
 * @param {number} firstScreenLines 첫 화면(뷰포트 안) 줄 수
 * @returns {boolean} true 면 "잴 내용이 없었다"(🟡 판정 보류)
 */
export function looksEmpty(bodyText, firstScreenLines) {
  // 🔴 `firstScreen < 8` 안전판은 말투와 **무관하게** 백지를 잡는다 — 지우지 말 것.
  //    문구가 아예 없는 화면(렌더 실패·로딩 고착)은 정규식이 못 본다.
  return EMPTY_HINT.test(bodyText ?? '') || Number(firstScreenLines ?? 0) < 8
}
